// ─── Build-time validation ───────────────────────────────────────────────────
// Catches missing level coverage and answer-position monoculture without
// weakening the runtime shuffle (which randomizes per render).

export function validateReviewCoverage(allLevelIds: string[]): string[] {
  const errors: string[] = []
  const covered = new Set(REVIEW_QUESTIONS.map(q => q.levelId))
  for (const id of allLevelIds) {
    if (!covered.has(id)) {
      errors.push(`Missing review coverage for level: ${id}`)
    }
  }
  // Answer-position monoculture check: no single position should hold >40% of answers.
  const posCount = [0, 0, 0, 0]
  for (const q of REVIEW_QUESTIONS) {
    posCount[q.answer] += 1
  }
  const total = REVIEW_QUESTIONS.length
  for (let i = 0; i < 4; i++) {
    const pct = posCount[i] / total
    if (pct > 0.4) {
      errors.push(`Answer position ${i} holds ${(pct * 100).toFixed(0)}% of answers (>40% monoculture)`)
    }
  }
  // Each question must have exactly 4 options
  for (const q of REVIEW_QUESTIONS) {
    if (q.options.length !== 4) {
      errors.push(`Question ${q.id} has ${q.options.length} options (expected 4)`)
    }
    if (q.answer < 0 || q.answer >= q.options.length) {
      errors.push(`Question ${q.id} has out-of-bounds answer index ${q.answer}`)
    }
  }
  return errors
}
